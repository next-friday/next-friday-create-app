import {afterAll, afterEach, describe, expect, it, vi} from "vitest";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import {execFileSync} from "node:child_process";
import path from "node:path";
import {tmpdir} from "node:os";

import {bootstrapBranch, commitProject, didInstallDependencies, initGit} from "../src/setup.ts";

const manifest = "package.json";
const localTool = "local-tool";
const root = mkdtempSync(path.join(tmpdir(), "create-app-test-"));

afterEach(() => {
  vi.unstubAllEnvs();
});

afterAll(() => {
  rmSync(root, {
    force: true,
    recursive: true,
  });
});

/**
 * Create a directory under the test root, and a repository in it when asked.
 * @param name - Directory name.
 * @param isRepository - Whether to run `git init` in it.
 * @returns The directory path.
 */
function makeDirectory(name: string, isRepository = false): string {
  const directory = path.join(root, name);

  mkdirSync(directory);

  if (isRepository) {
    expect(initGit(directory)).toBe("initialized");
  }

  return directory;
}

describe("initGit", () => {
  it("creates a repository on main", () => {
    const project = makeDirectory("project");

    expect(initGit(project)).toBe("initialized");
    expect(readFileSync(path.join(project, ".git", "HEAD"), "utf8")).toBe("ref: refs/heads/main\n");
  });

  it("leaves an existing repository alone", () => {
    expect(initGit(makeDirectory("existing", true))).toBe("existing");
  });

  it("does not nest a repository inside another", () => {
    const nested = path.join(makeDirectory("parent", true), "nested");

    mkdirSync(nested);
    expect(initGit(nested)).toBe("parent");
  });

  it("ignores a repository that the inherited GIT_DIR names", () => {
    const repository = makeDirectory("named-repository", true);
    const outside = makeDirectory("outside");

    vi.stubEnv("GIT_DIR", path.join(repository, ".git"));
    expect(initGit(outside)).toBe("initialized");
    expect(existsSync(path.join(outside, ".git", "HEAD"))).toBe(true);
  });

  it("reports a failure when Git is missing", () => {
    const bare = makeDirectory("bare");

    vi.stubEnv("PATH", "");
    expect(initGit(bare)).toBe("failed");
  });
});

const bootstrapMessage = "build(repo): bootstrap nodejs workspace\n\nGenerated by a test.\n";

/**
 * Create a repository with one file to commit, and give Git an author and no commit signing.
 * @param name - Directory name.
 * @returns The repository path.
 */
function makeProject(name: string): string {
  const project = makeDirectory(name, true);

  writeFileSync(path.join(project, manifest), "{}\n");
  vi.stubEnv("GIT_AUTHOR_NAME", "Test");
  vi.stubEnv("GIT_AUTHOR_EMAIL", "test@example.invalid");
  vi.stubEnv("GIT_COMMITTER_NAME", "Test");
  vi.stubEnv("GIT_COMMITTER_EMAIL", "test@example.invalid");
  vi.stubEnv("GIT_CONFIG_COUNT", "1");
  vi.stubEnv("GIT_CONFIG_KEY_0", "commit.gpgsign");
  vi.stubEnv("GIT_CONFIG_VALUE_0", "false");

  return project;
}

/**
 * Run Git in a repository and return its output.
 * @param project - Repository path.
 * @param gitArguments - Git arguments.
 * @returns Standard output.
 */
function git(project: string, gitArguments: string[]): string {
  return execFileSync("git", gitArguments, {
    cwd: project,
    encoding: "utf8",
  });
}

describe("commitProject", () => {
  it("commits every file on main with the message", () => {
    const project = makeProject("first-commit");

    expect(commitProject(project, bootstrapMessage)).toBe("committed");
    expect(git(project, ["log", "-1", "--format=%B"])).toBe(`${bootstrapMessage}\n`);
    expect(git(project, ["branch", "--show-current"])).toBe("main\n");
    expect(git(project, ["status", "--porcelain"])).toBe("");
  });

  it("commits on a new branch when the repository already has a commit", () => {
    const project = makeProject("imported");

    git(project, ["commit", "--allow-empty", "--message", "docs(repo): add readme"]);
    expect(commitProject(project, bootstrapMessage)).toBe("branched");
    expect(git(project, ["branch", "--show-current"])).toBe(`${bootstrapBranch}\n`);
  });

  it("does not commit when the branch already exists", () => {
    const project = makeProject("branch-taken");

    git(project, ["commit", "--allow-empty", "--message", "docs(repo): add readme"]);
    git(project, ["branch", bootstrapBranch]);
    expect(commitProject(project, bootstrapMessage)).toBe("branch-taken");
    expect(git(project, ["rev-list", "--count", "HEAD"])).toBe("1\n");
  });

  it("reports a commit that a Git hook stops", () => {
    const project = makeProject("hook-stops");
    const hook = path.join(project, ".git", "hooks", "pre-commit");

    writeFileSync(hook, "#!/bin/sh\nexit 1\n");
    chmodSync(hook, 0o755);
    expect(commitProject(project, bootstrapMessage)).toBe("failed");
    expect(git(project, ["rev-list", "--all", "--count"])).toBe("0\n");
  });
});

describe("didInstallDependencies", () => {
  it("installs the project dependencies", () => {
    const project = path.join(root, "installable");

    mkdirSync(path.join(project, localTool), {
      recursive: true,
    });

    writeFileSync(
      path.join(project, localTool, manifest),
      JSON.stringify({
        name: localTool,
        version: "1.0.0",
      }),
    );

    writeFileSync(
      path.join(project, manifest),
      JSON.stringify({
        name: "installable",
        version: "1.0.0",
        devDependencies: {
          [localTool]: "file:./local-tool",
        },
      }),
    );

    expect(didInstallDependencies(project)).toBe(true);
    expect(existsSync(path.join(project, "node_modules", localTool, manifest))).toBe(true);
  });

  it("runs install scripts in the project's own repository", () => {
    const project = path.join(root, "own-repository");
    const other = path.join(root, "other-repository");

    mkdirSync(project);
    mkdirSync(other);
    expect(initGit(project)).toBe("initialized");
    expect(initGit(other)).toBe("initialized");

    writeFileSync(
      path.join(project, manifest),
      JSON.stringify({
        name: "own-repository",
        version: "1.0.0",
        scripts: {
          prepare: "git config core.hooksPath .husky/_",
        },
      }),
    );

    vi.stubEnv("GIT_DIR", path.join(other, ".git"));
    expect(didInstallDependencies(project)).toBe(true);

    expect(readFileSync(path.join(project, ".git", "config"), "utf8")).toContain(
      "hooksPath = .husky/_",
    );

    expect(readFileSync(path.join(other, ".git", "config"), "utf8")).not.toContain("hooksPath");
  });

  it("reports a failed install", () => {
    const project = path.join(root, "broken");

    mkdirSync(project);
    writeFileSync(path.join(project, manifest), "{");
    expect(didInstallDependencies(project)).toBe(false);
  });
});
